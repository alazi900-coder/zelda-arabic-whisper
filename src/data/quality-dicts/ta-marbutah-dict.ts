const TA_LOOKUP = (() => {
  const m = new Map<string, string>();
  for (const [w, r] of TA_MARBUTAH_DICT) {
    if (w !== r) m.set(w.trim(), r);
  }
  return m;
})();

// See hamza-dict.ts — same prefix-aware boundary handling.
const PREFIX_RANGE = "\\u0621-\\u064A";
const BOUNDARY_CLASS = "\\s.,،؛:!؟?\\[\\](){}«»\"'";

export function findTaMarbutahErrors(text: string): {
  matches: Array<{ wrong: string; right: string }>;
  fix: string;
} {
  const matches: Array<{ wrong: string; right: string }> = [];
  let fix = text;
  const seen = new Set<string>();
  for (const [wrong, right] of TA_MARBUTAH_DICT) {
    if (wrong === right) continue;
    const re = new RegExp(
      `(^|[${BOUNDARY_CLASS}])([${PREFIX_RANGE}]{0,3}?)${escapeRegExp(wrong)}(?=$|[${BOUNDARY_CLASS}])`,
      "gu",
    );
    if (re.test(fix)) {
      if (!seen.has(wrong)) {
        matches.push({ wrong, right });
        seen.add(wrong);
      }
      fix = fix.replace(re, `$1$2${right}`);
    }
  }
  return { matches, fix };
}

function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

export function lookupTaMarbutah(token: string): string | null {
  return TA_LOOKUP.get(token.trim()) ?? null;
}
